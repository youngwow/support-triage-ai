def format_escalation(reason: str, history: list[ChatMessage]) -> str:
    """The exact console line the assignment requires on escalation."""
    dialog = " | ".join(message.as_line() for message in history)
    return f"[ESCALATION] Запрос передан оператору. Причина: {reason}, История диалога: {dialog}"
